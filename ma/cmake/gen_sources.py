#!/usr/bin/env python3
"""Generate CMake source lists from the original Visual Studio .vcproj files.

The .vcproj files are authoritative about which translation units belong to each
target; the original build system is long dead so we translate rather than
re-guess with globs. Re-run after changing a .vcproj:

    python3 cmake/gen_sources.py

Exclusions are deliberate and documented inline.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Pure-MFC translation units. mingw has no MFC, and these are debug-shell only
# (asset browser, vidmode picker, folder dialogs) rather than game code.
MFC_EXCLUDE = {
    "App/ma/win/ma_win.cpp",        # CWinApp entry point
    "App/ma/win/ma_winDlg.cpp",     # main CDialog
    "App/ma/win/PickAsset.cpp",     # CDialog asset browser
    "App/ma/win/VidMode.cpp",       # CDialog video mode picker
    "App/ma/win/InputEmulation.cpp",# CDialog input config
    "App/ma/win/pickdir.cpp",       # CFileDialog SHBrowseForFolder
    # Asset-authoring tools, not game runtime. These need MFC's CString and
    # CStringList (via App/ma/win/StdAfx.h -> <afxwin.h>). Nothing in the game
    # references CFileInfo or CMasterFileCompile -- only these files do --
    # and the retail master file is already available, so there is no need to
    # rebuild it here. Duplicates of both live in App/Spit and App/WavBanker,
    # which are not part of this target either.
    "App/ma/win/FileInfo.cpp",
    "App/ma/win/MasterFileCompile.cpp",
    "App/ma/win/winprintf.cpp",
    # A screenshot helper, and the only user of the Intel JPEG Library.
    # ijl15l.lib is an MSVC-compiled static library whose objects need
    # _except_list and _aullshr from the MSVC C runtime, which mingw does not
    # provide, so it cannot be linked here.
    "App/ma/win/ScreenGrab.cpp",
}

# Precompiled-header shims. The .vcproj builds via StdAfx.cpp/fangpch.cpp; we
# use real headers instead, so these would only duplicate.
PCH_EXCLUDE = {
    "App/ma/win/StdAfx.cpp",
    "App/ma/win/fangpch.cpp",
}


def relpaths(vcproj):
    """Yield project-relative paths from a VS .vcproj, in document order."""
    with open(vcproj, encoding="latin-1") as fh:
        text = fh.read()
    base = os.path.dirname(vcproj)
    for match in re.finditer(r'RelativePath="([^"]+)"', text):
        raw = match.group(1).replace("\\", "/")
        yield os.path.normpath(os.path.join(base, raw))


def sources(vcproj, drop=()):
    """Compiled translation units, as paths relative to ROOT, excluding missing."""
    out, missing = [], []
    for path in relpaths(vcproj):
        ext = os.path.splitext(path)[1].lower()
        if ext not in (".cpp", ".c"):
            continue
        key = os.path.relpath(path, ROOT).replace(os.sep, "/")
        if key in drop:
            continue
        if not os.path.exists(path):
            missing.append(key)
            continue
        out.append(key)
    return out, missing


def emit(varname, paths, path, header):
    with open(path, "w") as fh:
        fh.write("# Generated by cmake/gen_sources.py -- do not edit.\n")
        fh.write(f"# {header}\n")
        fh.write(f"set({varname}\n")
        for p in sorted(set(paths)):
            fh.write(f"    {p}\n")
        fh.write(")\n")
    return len(set(paths))


def main():
    outdir = os.path.join(ROOT, "cmake")
    os.makedirs(outdir, exist_ok=True)

    ma, ma_missing = sources(
        os.path.join(ROOT, "App/ma/win/ma_win.vcproj"), MFC_EXCLUDE | PCH_EXCLUDE
    )
    n = emit("MA_WIN_SOURCES", ma, os.path.join(outdir, "sources_ma_win.cmake"),
             "from App/ma/win/ma_win.vcproj minus MFC shell and PCH shims")
    print(f"ma_win:   {n} sources")

    fang, fang_missing = sources(os.path.join(ROOT, "Lib/Fang2/dx/win/fang2win.vcproj"))
    n = emit("FANG2WIN_SOURCES", fang, os.path.join(outdir, "sources_fang2win.cmake"),
             "from Lib/Fang2/dx/win/fang2win.vcproj")
    print(f"fang2win: {n} sources")

    # SmallAMX.vcproj is zero bytes in this dump; the .dsp is intact.
    amx = ["Lib/SmallAMX/amx.c", "Lib/SmallAMX/amxcons.c", "Lib/SmallAMX/amxcore.c"]
    n = emit("SMALLAMX_SOURCES", amx, os.path.join(outdir, "sources_smallamx.cmake"),
             "SmallAMX interpreter (amx.c, amxcons.c, amxcore.c)")
    print(f"smallamx: {n} sources")

    missing = ma_missing + fang_missing
    if missing:
        print(f"\n{len(missing)} listed sources absent from this dump:", file=sys.stderr)
        for m in missing:
            print(f"  {m}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
